"""Tests for tools/generate.py (tools/check.sh runs them in jamovi's bundled Python)."""
import copy
import importlib.util
import json
import tempfile
import unittest
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
_spec = importlib.util.spec_from_file_location("generate", ROOT / "tools" / "generate.py")
generate = importlib.util.module_from_spec(_spec)
_spec.loader.exec_module(generate)

VALID = {
    "name": "probe", "title": "Probe", "menuGroup": "ClinicoPathPj", "version": "0.1.0",
    "options": [
        {"name": "dep", "type": "Variable", "title": "Outcome", "required": True},
        {"name": "lvl", "type": "Level", "title": "Level", "variable": "(dep)"},
        {"name": "ci", "type": "Number", "title": "CI", "default": 95, "min": 50, "max": 99},
    ],
    "results": [{"name": "tab", "type": "Table", "title": "Tab", "columns": [
        {"name": "p", "title": "p", "type": "number", "format": "zto,pvalue"}]}],
}


def parse_generated(text):
    first, rest = text.split("\n", 1)
    assert first.startswith("# Generated by tools/generate.py"), first
    return json.loads(rest)


class GeneratedFiles(unittest.TestCase):
    def test_committed_files_are_current(self):
        self.assertEqual(generate.main(["--check"]), 0, "run tools/build.R (or tools/generate.py)")

    def test_render_is_deterministic(self):
        for path in sorted(generate.ANALYSES.rglob("*.py")):
            self.assertEqual(generate.render(path), generate.render(path))

    def test_pywelch_contract(self):
        files = generate.render(generate.ANALYSES / "jjstatsplot/pywelch.py")
        options = parse_generated(files[ROOT / "jamovi" / "pywelch.a.yaml"])["options"]
        self.assertEqual([options[0]["name"], options[-1]["name"]], ["data", "showConsole"])
        self.assertFalse(any("required" in option for option in options))  # jamovi would skip .run()
        by_name = {option["name"]: option for option in options}
        self.assertIsNone(by_name["dep"]["default"])
        self.assertNotIn("default", by_name["refLevel"])
        items = parse_generated(files[ROOT / "jamovi" / "pywelch.r.yaml"])["items"]
        self.assertEqual(items[-1], {"name": "console", "title": "Python console",
                                     "type": "Preformatted", "visible": "(showConsole)"})
        b_r = files[ROOT / "R" / "pywelch.b.R"]
        self.assertIn('required = c(dep = "Outcome", group = "Group")', b_r)
        self.assertIn("arrays = character(0)", b_r)

    def test_variables_are_sent_as_arrays(self):
        b_r = generate.render(generate.ANALYSES / "descriptives/pydescriptives.py")[ROOT / "R" / "pydescriptives.b.R"]
        self.assertIn('arrays = c("vars")', b_r)

    def test_numeric_only_options_are_marked_for_conversion(self):
        self.assertIn('numeric = c("vars")', generate.render(
            generate.ANALYSES / "descriptives/pydescriptives.py")[ROOT / "R" / "pydescriptives.b.R"])
        self.assertIn('numeric = c("dep")', generate.render(
            generate.ANALYSES / "jjstatsplot/pywelch.py")[ROOT / "R" / "pywelch.b.R"])  # group (factor) is not


class Validation(unittest.TestCase):
    def assertRejected(self, change, fragment):
        spec = copy.deepcopy(VALID)
        change(spec)
        with self.assertRaisesRegex(generate.SpecError, fragment):
            generate.validate(spec, spec["name"])

    def test_valid_spec_passes(self):
        generate.validate(copy.deepcopy(VALID), "probe")

    def test_variable_after_other_options(self):
        self.assertRejected(lambda s: s["options"].append(
            {"name": "late", "type": "Variable", "title": "Late"}), "must come before")

    def test_level_needs_single_variable(self):
        self.assertRejected(lambda s: s["options"][1].update(variable="(nope)"), "Level 'lvl' needs")

    def test_reserved_names(self):
        self.assertRejected(lambda s: s["results"][0].update(name="console"), "reserved")
        self.assertRejected(lambda s: s["options"][0].update(name="cpjNotice1"), "reserved")

    def test_format_tokens(self):
        self.assertRejected(lambda s: s["results"][0]["columns"][0].update(format="zto:3"), "format must be")

    def test_number_default_in_range(self):
        self.assertRejected(lambda s: s["options"][2].update(default=100), "between min and max")

    def test_unsupported_option_type(self):
        self.assertRejected(lambda s: s["options"].append({"name": "alt", "type": "Unknown", "title": "Alt"}),
                            "not supported")

    def test_name_is_independent_of_source_filename(self):
        generate.validate(copy.deepcopy(VALID), "other")

    def test_names_jamovi_or_r_cannot_use(self):
        self.assertRejected(lambda s: s["options"][2].update(name="next"), "reserved")    # R keyword
        self.assertRejected(lambda s: s["options"][2].update(name="levels"), "reserved")  # jmvcore Options member
        self.assertRejected(lambda s: s["results"][0].update(name="title"), "reserved")   # results member

    def test_titles_that_break_the_build_or_the_display(self):
        self.assertRejected(lambda s: s.update(title='Welch "t" test'), "quotes")
        self.assertRejected(lambda s: s.update(title="two\nlines"), "control characters")
        self.assertRejected(lambda s: s["results"][0].update(title="(SE)"), "parentheses")
        self.assertRejected(lambda s: s["results"][0].update(title="Mean {x}"), "parentheses")
        self.assertRejected(lambda s: s["results"][0]["columns"][0].update(title="p [ref]"), "translation")

    def test_numeric_options_can_have_one_sided_bounds(self):
        spec=copy.deepcopy(VALID)
        del spec['options'][2]['max']
        generate.validate(spec,'example')
        spec['options'][2]['min']=100
        with self.assertRaisesRegex(generate.SpecError,'between min and max'):
            generate.validate(spec,'example')

    def test_explicit_numeric_factor_conversion_is_bridge_only(self):
        spec=copy.deepcopy(VALID)
        spec['options'][0].update(permitted=['numeric','factor'],coerceNumeric=True)
        generate.validate(spec,'example')
        self.assertNotIn('coerceNumeric',generate.a_yaml(spec)['options'][1])
        self.assertIn('numeric = c("dep")',generate.b_r(spec,'example'))

    def test_option_value_types(self):
        self.assertRejected(lambda s: s["options"][1].update(allowNone="yes"), "allowNone")
        self.assertRejected(lambda s: s["options"][2].update(max=float("inf")), "finite")
        self.assertRejected(lambda s: s["options"][0].update(permitted=["id"]), "'id' needs 'factor'")
        self.assertRejected(lambda s: s.update(results={"tab": {}}), "must be lists")


class NewTypes(unittest.TestCase):
    """List/Integer/String options, event levels, Image/Text results and result visibility."""

    def spec(self):
        spec = copy.deepcopy(VALID)
        spec["options"][1].update(role="event")
        spec["options"] += [
            {"name": "method", "type": "List", "title": "Method", "default": "a",
             "options": [{"name": "a", "title": "A"}, {"name": "b", "title": "B"}]},
            {"name": "draws", "type": "Integer", "title": "Draws", "default": 1000, "min": 100, "max": 100000},
            {"name": "props", "type": "String", "title": "Proportions", "default": "0.2, 0.8"},
            {"name": "showPlot", "type": "Bool", "title": "Plot", "default": True},
        ]
        spec["results"] += [
            {"name": "summary", "type": "Text", "title": "Interpretation"},
            {"name": "fig", "type": "Image", "title": "Figure", "plot": "interval", "visible": "(showPlot)"},
        ]
        return spec

    def test_valid_and_emitted(self):
        spec = self.spec()
        generate.validate(spec, "probe")
        options = {o["name"]: o for o in generate.a_yaml(spec)["options"]}
        self.assertTrue(options["lvl"]["allowNone"])          # role: event -> nothing preselected
        self.assertNotIn("role", options["lvl"])
        self.assertEqual(options["method"]["options"][1], {"name": "b", "title": "B"})
        items = {i["name"]: i for i in generate.r_yaml(spec)["items"]}
        self.assertEqual(items["fig"]["renderFun"], ".plot")
        self.assertIs(items["fig"]["requiresData"], False)   # the renderer reads only image$state
        self.assertEqual(items["fig"]["visible"], "(showPlot)")
        self.assertEqual(items["summary"]["type"], "Text")
        b_r = generate.b_r(spec, "header")
        self.assertIn('events = c(lvl = "dep")', b_r)
        self.assertIn("checkpoint = function() private$.checkpoint(flush = FALSE)", b_r)
        self.assertIn(".plot = function(image, ggtheme, theme, ...) .cpjPlot(image, ggtheme, theme)", b_r)

    def assertRejected(self, change, fragment):
        spec = self.spec()
        change(spec)
        with self.assertRaisesRegex(generate.SpecError, fragment):
            generate.validate(spec, "probe")

    def test_list_rules(self):
        self.assertRejected(lambda s: s["options"][3].update(default="z"), "default must be one of")
        self.assertRejected(lambda s: s["options"][3].update(options=[{"name": "a", "title": "A"}]), "two options")

    def test_integer_rules(self):
        self.assertRejected(lambda s: s["options"][4].update(default=10.5), "whole-number")
        self.assertRejected(lambda s: s["options"][4].update(default=50), "between min and max")

    def test_image_rules(self):
        self.assertRejected(lambda s: s["results"][2].update(plot="pie"), "plot must be one of")
        self.assertRejected(lambda s: s["results"][2].update(width=5000), "between 200 and 2000")
        self.assertRejected(lambda s: s["results"][2].update(visible="(nope)"), "naming a Bool option")

    def test_level_role(self):
        self.assertRejected(lambda s: s["options"][1].update(role="reference"), "role must be 'event'")

    def test_column_visibility(self):
        spec = self.spec()
        spec["results"][0]["columns"].append({"name": "exact", "title": "p (exact)", "type": "number", "visible": False})
        generate.validate(spec, "probe")
        columns = generate.r_yaml(spec)["items"][0]["columns"]
        self.assertIs(columns[-1]["visible"], False)  # sent with the results, not shown
        self.assertRejected(lambda s: s["results"][0]["columns"][0].update(visible="(nope)"), "visible must be True")


class ReadSpec(unittest.TestCase):
    def read(self, source):
        with tempfile.TemporaryDirectory() as folder:
            path = Path(folder) / "probe.py"
            path.write_text(source, encoding="utf-8")
            return generate.read_spec(path)

    def test_duplicate_keys_rejected(self):
        with self.assertRaisesRegex(generate.SpecError, "duplicate key"):
            self.read('SPEC = {"name": "a", "name": "b"}\n')

    def test_computed_values_rejected(self):
        with self.assertRaisesRegex(generate.SpecError, "plain literal"):
            self.read('SPEC = {"title": "a" + str(1)}\n')

    def test_missing_spec_rejected(self):
        with self.assertRaisesRegex(generate.SpecError, "exactly one"):
            self.read("def run(data, options, out):\n    pass\n")

    def test_analysis_is_not_executed(self):
        spec = self.read('raise SystemExit("imported!")\nSPEC = {"name": "probe"}\n')
        self.assertEqual(spec, {"name": "probe"})


if __name__ == "__main__":
    unittest.main()
