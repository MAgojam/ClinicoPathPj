const assert=require('node:assert/strict'),fs=require('node:fs'),{JSDOM}=require('jsdom');
const errors=[];
const dom=new JSDOM(fs.readFileSync(process.argv[2],'utf8'),{runScripts:'dangerously',beforeParse(w){
 w.addEventListener('error',e=>errors.push(e.message));
 w.setOption=()=>{throw Error('Tree inspection must not change native options');};
 w.fetch=()=>{throw Error('Tree inspection must stay local');};
}});
const d=dom.window.document;
assert.deepEqual(errors,[]);
const rowBranches=d.querySelectorAll('.tree-branch[data-axis="rows"]');
assert.equal(rowBranches.length,3);
rowBranches[0].focus();
assert.match(d.querySelector('.detail').textContent,/Members \(2\): 2, 7/);
const selected=()=>Array.from(d.querySelectorAll('.grid button[aria-pressed="true"]'));
assert.equal(selected().length,6);
assert(selected().every(b=>/^Row (2|7),/.test(b.getAttribute('aria-label'))));
assert.equal(d.querySelectorAll('.scatter-view circle[aria-pressed="true"]').length,2);
rowBranches[0].dispatchEvent(new dom.window.KeyboardEvent('keydown',{key:' ',bubbles:true}));
assert.equal(selected().length,6);
rowBranches[2].dispatchEvent(new dom.window.MouseEvent('click',{bubbles:true}));assert.equal(selected().length,12);
const markerBranches=d.querySelectorAll('.tree-branch[data-axis="markers"]');
assert.equal(markerBranches.length,2);markerBranches[0].focus();
assert.equal(selected().length,8);
assert(selected().every(b=>/, (a|c), raw/.test(b.getAttribute('aria-label'))));
assert.equal(d.querySelectorAll('.scatter-view circle[aria-pressed="true"]').length,0);
d.querySelector('.clear').click();assert.equal(selected().length,0);
d.querySelector('.grid button').click();assert.equal(selected().length,3);
assert.equal(d.querySelector('unsafe'),null);assert.deepEqual(errors,[]);
console.log('IHC dendrogram row/marker membership, linked highlighting, keyboard, clear and no refit PASSED');
dom.window.close();
