test_that("generated metadata stays a single YAML document with an idempotent example entry", {
    root <- tempfile("cpj-metadata-")
    dir.create(root); dir.create(file.path(root, "jamovi")); dir.create(file.path(root, "data"))
    writeLines(c("Package: ClinicoPathPj", "Version: 0.2.0", "Date: 2026-10-25"), file.path(root, "DESCRIPTION"))
    path <- file.path(root, "jamovi", "0000.yaml")
    writeLines(c("---", "name: ClinicoPathPj", "version: 0.1.0", "date: '2026-10-18'", "analyses: []", "..."), path)
    file.create(file.path(root, "data", "python_core_examples.omv"))
    script <- file.path(Sys.getenv("CPJ_ROOT", unset = "../.."), "tools", "sync-metadata.R")
    env <- new.env()
    sys.source(script, envir = env)
    expect_no_error(env$sync_module_metadata(root))
    parsed <- yaml::read_yaml(path)
    expect_equal(parsed$version, "0.2.0")
    expect_equal(parsed$date, "2026-10-25")
    expect_equal(parsed$datasets[[1]]$path, "python_core_examples.omv")
    first <- readLines(path)
    env$sync_module_metadata(root)
    expect_equal(readLines(path), first)
})
