study_options <- list(study='Study',true_positives='TP',false_positives='FP',
                      false_negatives='FN',true_negatives='TN')
study_fixture <- function() read.csv(testthat::test_path('..','..','data','python_diagnostic_study_examples.csv'),
                                    na.strings='',check.names=FALSE)

test_that('raw study estimates agree with base R score intervals', {
    d <- study_fixture()
    got <- do.call(pydiagnosticmeta,c(list(data=d,forest_plot=TRUE),study_options))
    expect_equal(unname(as.numeric(got$cohort$asDF[1,])),c(12,8,4,3,1,1))
    tab <- got$studies$asDF
    expect_equal(tab$sourceID,as.character(1:8))
    expect_equal(tab$tp,d$TP[1:8])
    expect_equal(tab$sensitivity,c(.8,.9,0,.8,1,.9,.8,.9))
    expect_equal(tab$specificity,c(.9,.8,.75,1,0,.8,.9,.9))
    for (i in seq_len(8)) {
        se <- suppressWarnings(prop.test(d$TP[i],d$TP[i]+d$FN[i],correct=FALSE)$conf.int)
        sp <- suppressWarnings(prop.test(d$TN[i],d$TN[i]+d$FP[i],correct=FALSE)$conf.int)
        expect_equal(c(tab$seLower[i],tab$seUpper[i]),as.numeric(se),tolerance=1e-12)
        expect_equal(c(tab$spLower[i],tab$spUpper[i]),as.numeric(sp),tolerance=1e-12)
    }
    expect_equal(got$sensitivityPlot$state$data$estimate,tab$sensitivity)
    expect_equal(got$specificityPlot$state$data$estimate,tab$specificity)
    expect_equal(got$excluded$asDF$sourceID,as.character(9:12))
    expect_match(got$summary$content,'No continuity correction')
})

test_that('numeric factor labels are participant counts and large counts survive transport', {
    d <- study_fixture();d$TP <- factor(d$TP)
    expect_error(do.call(pydiagnosticmeta,c(list(data=d),study_options)),'numeric variable')
    # jamovi numeric Nominal/Ordinal columns carry numeric values separately
    # from factor codes. A plain text factor must remain rejected.
    attr(d$TP,'values') <- as.numeric(levels(d$TP))
    got <- do.call(pydiagnosticmeta,c(list(data=d),study_options))
    expect_equal(got$studies$asDF$tp[1],80)
    d <- data.frame(Study='Large',TP=3e9,FP=1,FN=1,TN=2)
    got <- do.call(pydiagnosticmeta,c(list(data=d),study_options))
    expect_equal(got$studies$asDF$tp,3e9)
    expect_equal(got$studies$asDF$sensitivity,3e9/(3e9+1))
})

test_that('study review clears stale results and recovers across input transitions', {
    d <- study_fixture();rownames(d) <- as.character(seq(3,25,2))
    opts <- do.call(pydiagnosticmetaOptions$new,c(study_options,list(forest_plot=FALSE,show_explorer=TRUE,show_report=TRUE)))
    a <- pydiagnosticmetaClass$new(options=opts)
    a$.setReadDatasetSource(function(...) d)
    a$.setReadDatasetHeaderSource(function(...) d)
    a$init();a$run()
    expect_equal(a$results$studies$asDF$sourceID,rownames(d)[1:8])
    expect_match(a$results$explorer$content,'Linked study inspector')
    expect_false(is.null(a$results$sensitivityPlot$state))
    role <- opts$option('true_negatives');role$value<-NULL;a$init();a$run()
    expect_equal(a$results$studies$rowCount,0)
    expect_equal(a$results$cohort$rowCount,0)
    expect_null(a$results$sensitivityPlot$state)
    expect_false(grepl('Linked study inspector',a$results$explorer$content,fixed=TRUE))
    role$value<-'TN';a$init();a$run()
    expect_equal(a$results$studies$rowCount,8)
    strict <- opts$option('reject_invalid');strict$value<-TRUE;a$init()
    expect_error(a$run(),'4 study row')
    expect_equal(a$results$studies$rowCount,0)
    expect_null(a$results$specificityPlot$state)
    expect_false(grepl('Linked study inspector',a$results$explorer$content,fixed=TRUE))
    strict$value<-FALSE;d$TP[]<-NA_real_;a$init();a$run()
    expect_equal(a$results$cohort$asDF$retained,0)
    expect_equal(a$results$excluded$rowCount,12)
    expect_null(a$results$sensitivityPlot$state)
    expect_false(grepl('Linked study inspector',a$results$explorer$content,fixed=TRUE))
    d <- study_fixture();a$init();a$run()
    fresh <- do.call(pydiagnosticmeta,c(list(data=d,forest_plot=TRUE,show_report=TRUE),study_options))
    expect_equal(a$results$studies$asDF,fresh$studies$asDF)
    ci <- opts$option('confidence_level');ci$value<-99;a$init();a$run()
    expect_lt(a$results$studies$asDF$seLower[1],fresh$studies$asDF$seLower[1])
    expect_gt(a$results$studies$asDF$seUpper[1],fresh$studies$asDF$seUpper[1])
    expect_match(a$results$explorer$content,'Linked study inspector')
    explorer <- opts$option('show_explorer');explorer$value<-FALSE;a$init();a$run()
    expect_false(grepl('Linked study inspector',a$results$explorer$content,fixed=TRUE))
    expect_null(a$results$sensitivityPlot$state)
    expect_equal(a$results$studies$asDF$sensitivity,fresh$studies$asDF$sensitivity)
})

test_that('explicit study inclusion updates native results and rejects stale input snapshots', {
    d <- study_fixture()
    opts <- do.call(pydiagnosticmetaOptions$new,c(study_options,
        list(enable_inclusion=TRUE,show_explorer=TRUE,show_report=TRUE)))
    a <- pydiagnosticmetaClass$new(options=opts)
    a$.setReadDatasetSource(function(...) d)
    a$.setReadDatasetHeaderSource(function(...) d)
    a$init();a$run()
    expect_equal(a$results$inclusion$asDF$included,8)
    html <- a$results$explorer$content
    encoded <- sub('.*payload=(\\{.*\\}),rows=payload.studies;.*','\\1',html)
    payload <- jsonlite::fromJSON(encoded)
    snapshot <- payload$inclusion$snapshot
    definition <- opts$option('inclusionDefinition')
    definition$value <- jsonlite::toJSON(list(version=1L,rows=c('7','1'),snapshot=snapshot),auto_unbox=TRUE)
    a$init();a$run()
    expect_equal(a$results$studies$asDF$sourceID,c('1','7'))
    expect_equal(a$results$inclusion$asDF$included,2)
    expect_equal(a$results$inclusion$asDF$omitted,6)
    expect_equal(a$results$cohort$asDF$retained,8)
    expect_equal(a$results$sensitivityPlot$state$data$estimate,c(.8,.8))
    ci <- opts$option('confidence_level');ci$value <- 99L;a$init();a$run()
    expect_equal(a$results$inclusion$asDF$included,2)
    expect_match(a$results$inclusion$asDF$status,'Applied to current input')
    d$TP[1] <- 81;a$init();a$run()
    expect_equal(a$results$studies$rowCount,0)
    expect_equal(a$results$inclusion$asDF$included,0)
    expect_match(a$results$inclusion$asDF$status,'Input changed')
    expect_null(a$results$sensitivityPlot$state)
    expect_match(a$results$explorer$content,'Study inclusion preview')
    enabled <- opts$option('enable_inclusion');enabled$value <- FALSE;a$init();a$run()
    expect_equal(a$results$studies$rowCount,8)
    enabled$value <- TRUE;definition$value <- '';a$init();a$run()
    expect_equal(a$results$inclusion$asDF$included,8)
    html <- a$results$explorer$content
    payload <- jsonlite::fromJSON(sub('.*payload=(\\{.*\\}),rows=payload.studies;.*','\\1',html))
    definition$value <- jsonlite::toJSON(list(version=1L,rows=list(),snapshot=payload$inclusion$snapshot),auto_unbox=TRUE)
    a$init();a$run()
    expect_equal(a$results$studies$rowCount,0)
    expect_match(a$results$inclusion$asDF$status,'Applied to current input')
    expect_null(a$results$specificityPlot$state)
    expect_match(a$results$explorer$content,'Study inclusion preview')
    definition$value <- 'invalid';a$init()
    expect_error(a$run(),'not valid JSON')
    expect_equal(a$results$inclusion$rowCount,0)
    expect_false(grepl('Study inclusion preview',a$results$explorer$content,fixed=TRUE))
})
