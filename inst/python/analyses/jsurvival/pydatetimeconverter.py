def run(data, options, out):
    r=calculate(data,options)
    if options.get('show_quality_metrics',False):
        out.row('quality',input=r['total'],parsed=r['parsed'],invalid=r['invalid'],missing=r['missing'],success=r['success'])
    ids=out.row_ids if out.row_ids is not None else [str(i+1) for i in range(r['total'])]
    for source,row in list(zip(ids,r['rows']))[:r['preview_limit']]:out.row('preview',source=source,**row)
    if r['total']>r['preview_limit']:out.info(f"The preview shows the first {r['preview_limit']} source rows; quality counts and saved outputs use all {r['total']} supplied rows.")
    if r['invalid']:out.warn(f"{r['invalid']} nonmissing value(s) failed the explicit format/calendar check; their saved outputs remain missing. Inspect Status and Reason.")
    if r['early_excel']:out.warn('Excel 1900 serials below 61 use the frozen R origin convention 1899-12-30. These do not reproduce Excel’s pre-March-1900 calendar, including its fictitious leap day; verify early serials.')
    if not r['parsed']:out.info('No valid datetime was parsed. No instant or component has been fabricated.')
    if out.row_ids is not None:
        out.column('corrected_datetime_numeric',r['epoch'],measure_type='continuous',title='Unix epoch seconds (UTC)',description='Seconds since 1970-01-01 00:00:00 UTC; failed/missing input remains missing')
        corrected=[v['corrected'] for v in r['rows']]
        labels=list(dict.fromkeys(v for v in corrected if v is not None)) or ['(No parsed dates)']
        out.column('corrected_datetime_char',[None if v is None else labels.index(v) for v in corrected],levels=labels,measure_type='nominal',title='Standardized UTC datetime labels',description='Explicit-format ISO datetime labels in UTC; failed/missing input remains missing')
        titles={'year':'Year','month':'Month','monthname':'Month name','day':'Day of month','hour':'Hour','minute':'Minute','second':'Second','dayname':'Day name','weeknum':'Week (Jan-1 blocks)','quarter':'Quarter','dayofyear':'Day of year'}
        for name in COMPONENTS:
            values=[v[name] for v in r['rows']]
            if name in ('monthname','dayname'):
                levels=MONTHS if name=='monthname' else DAYS
                out.column(name+'_out',[None if v is None else levels.index(v) for v in values],levels=levels,measure_type='nominal',title=titles[name]+' (UTC)',description='Calendar component in UTC; fixed English labels; failed/missing input remains missing')
            else:out.column(name+'_out',values,measure_type='continuous',title=titles[name]+' (UTC)',description='Calendar component in UTC; week uses Jan-1 blocks, not ISO; failed/missing input remains missing')
    scope=(f"Input rows: {r['total']}; parsed: {r['parsed']}; invalid: {r['invalid']}; missing or blank: {r['missing']}. Explicit format: {r['fmt']}; timezone: UTC. "
        'Success percentages use nonmissing input; invalid and missing rows remain distinct and retain their source positions. '
        'This strict core requires four-digit years and explicit formats. It does not guess day/month order, infer an Excel epoch or use the system timezone. '
        'Auto-detection, named timezones/DST, two-digit-year policies and native Date/POSIX input classes are pending. '
        'Date-only values mean midnight UTC. Excel day fractions round to whole seconds using ties-to-even, as in the frozen R baseline; Unix/text times support microseconds. '
        'Week numbers are Jan-1 seven-day blocks, not ISO or epidemiological weeks. Month/day names use fixed English labels. '
        'Parsing success does not validate a clinical date, event origin or follow-up interval; inspect the original and converted values before downstream use.')
    out.markdown('summary',md_escape(scope))
    if options.get('show_summary',False):out.markdown('report',md_escape(f"Using explicit {r['fmt']} interpretation in UTC, {r['parsed']} of {r['total']} supplied records were parsed; {r['invalid']} were invalid and {r['missing']} were missing or blank. No rows were dropped. These counts assess conversion, not clinical date validity."))
    if options.get('show_explanations',False):out.markdown('about','This deterministic transformation uses Python calendar validation and UTC arithmetic. Supported text separators are matching hyphens or slashes, a space or T before time, and an optional Z on time-bearing values. Offsets, localized month names, two-digit years, leap seconds and invalid calendars are rejected. Standardized text is saved as nominal ISO-UTC labels; numeric output is Unix seconds. Save only the columns you need. Numeric epochs identify instants, not an elapsed survival duration. Excel 1900 uses 1899-12-30 and Excel 1904 uses 1904-01-01; choose the correct origin explicitly.')
