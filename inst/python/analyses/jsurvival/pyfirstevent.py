def run(data, options, out):
    r = calculate(data,options)
    if r['pending']:
        out.info(r['pending']);out.markdown('summary',md_escape(r['pending']));return
    out.row('cohort',input=r['n'],retained=r['retained'],invalid=r['invalid'],missing=r['missing'],ties=r['ties'],late=r['late'])
    if r['identity']:
        identity=r['identity']
        out.row('identityAudit',**{k:identity[k] for k in ['input','known','missing','subjects','repeatedSubjects','repeatedRows']})
        for row in identity['repeated'][:20]:out.row('repeatedSubjects',**row)
        out.markdown('identityPolicy',md_escape(
            'IDs use exact text or factor labels across ALL supplied records, including records with unusable endpoints. Missing values and wholly blank IDs are unknown; nonblank IDs retain leading/trailing spaces and leading zeros. Literal NA is a known ID. '
            'Repeated IDs are listed in first appearance order, at most 20; all repeats contribute to the audit. Endpoint preparation still operates on each supplied row. There is no patient aggregation, deduplication, history ordering or patient-level first-event inference. '
            'Requiring one record per subject blocks preparation when an ID is missing or repeated. Unique IDs do not establish independent observations or sufficient clinical follow-up.'))
        if identity['missing'] or identity['repeatedSubjects']:
            out.warn(f"Subject audit: {identity['missing']} records have unknown IDs; {identity['repeatedSubjects']} IDs repeat across {identity['repeatedRows']} records. Prepared outputs remain record-level; resolve the intended observational unit before patient-level inference.")
        if identity['repeatedSubjects']>20:out.info('Only the first 20 repeated IDs are listed; all supplied records contribute to identity accounting.')
    if r['admin']['enabled']:out.row('adminAudit',**{k:v for k,v in r['admin'].items() if k!='enabled'})
    for row in r['mapping']:out.row('mapping',**row)
    for row in r['counts']:out.row('counts',**row)
    if options.get('showPreview',True):
        ids=out.row_ids if out.row_ids is not None else [str(i+1) for i in range(r['n'])]
        for source,row in list(zip(ids,r['rows']))[:r['limit']]:out.row('preview',sourceID=source,**row)
        if r['n']>r['limit']:out.info('The preview is bounded; accounting and saved outputs retain all supplied rows.')
    if options.get('showPlot',False):out.plot('distribution',[dict(label=row['label'],value=row['n'],group='Prepared rows') for row in r['counts']],xlab='Composite status',ylab='Supplied rows')
    if out.row_ids is not None:
        out.column('timeOut',r['time'],measure_type='continuous',title='Composite time',description=('Administrative cutoff '+str(r['admin']['cutoff'])+' applied after common observation horizon. ' if r['admin']['enabled'] else '')+'Minimum component event/follow-up duration. A common origin and units are required; negative or incomplete records remain missing.')
        out.column('statusOut',r['status'],levels=['Censored','Event'],measure_type='nominal',title='Composite status',description=('Administrative cutoff '+str(r['admin']['cutoff'])+'; event at cutoff retained. ' if r['admin']['enabled'] else '')+'0=Censored; 1=Event at common follow-up horizon; event wins an exact event/censor tie. Not a competing-risk code.')
        out.column('sourceOut',r['source'],levels=SOURCES+(['Administrative cutoff'] if r['admin']['enabled'] else []),measure_type='nominal',title='Determining component',description='Audit source only; not a cause-specific event indicator.')
    if r['invalid']:out.warn(f"{r['invalid']} row(s) have a negative duration; all saved outputs remain missing.")
    if r['missing']:out.warn(f"{r['missing']} row(s) have incomplete component status/time; all saved outputs remain missing. A known event cannot establish a first event when the other component is unknown.")
    if r['late']:out.info(f"{r['late']} known event(s) occur after the other component's event-free follow-up ended. The composite is censored at the earlier common observation horizon.")
    out.markdown('summary',md_escape(
        'Policy: two-component composite with a common origin and units. Each time is time to its component event when status=1, otherwise time through which that component is known event-free. '
        'Before optional administrative censoring, composite time is the minimum of those two times. The composite is an event only if a selected component event occurs at that minimum; an event wins an exact event/censor tie. Simultaneous component events are labelled Both components. '
        'A later event is not carried back across an earlier end of observation for the other component. Missing status or time makes all three outputs missing; no partial-record event override is used. Negative durations are invalid; zero is permitted. '
        'Explicit event and event-free levels are required; other observed levels must be recoded first. Rows are supplied records, not deduplicated patients. Verify one record per intended observational unit. '
        'This is numeric data preparation, not clinical endpoint adjudication, independent-censoring validation, competing-risk coding or a fitted survival model. No clinical RFS/PFS/DFS definition is assigned.'))
    if r['admin']['enabled']:
        out.info(f"Administrative cutoff {r['admin']['cutoff']}: {r['admin']['shortened']} records shortened, including {r['admin']['eventsRemoved']} events changed to censored. Events exactly at the cutoff remain events. Invalid/incomplete records remain missing.")
        out.markdown('summary',md_escape(
            'Two-component policy: first construct the unadjusted minimum component observation time, with an event at that minimum winning an exact event/censor tie. '
            f"Then apply the explicitly supplied administrative cutoff {r['admin']['cutoff']} in the same duration units from the same origin: only times strictly greater than the cutoff are shortened and coded Censored. Events exactly at the cutoff remain Event. "
            'The preview includes unadjusted time/status and whether the cutoff changed the record. The determining-component output records Administrative cutoff for shortened records; it is an audit source, not a cause-specific indicator. '
            'Negative/incomplete component records remain missing even if the cutoff precedes a known component event. Administrative censoring does not repair unknown ascertainment. '
            'Both statuses must use explicitly selected event/event-free levels. Event-free times mean duration through which each component is known event-free; a later event cannot override earlier loss of follow-up for the other component. '
            'Verify a common origin, units and one record per intended unit. No dates, patient hierarchy, clinical endpoint adjudication, independent-censoring validation, competing-risk coding or survival model are inferred.'))
    if options.get('showReport',False):out.markdown('report',md_escape(f"Prepared {r['retained']} of {r['n']} records: {r['status'].count(1)} events and {r['status'].count(0)} censored, with {r['invalid']} invalid and {r['missing']} incomplete records. Event/censor ties: {r['ties']}; events beyond common follow-up: {r['late']}. These counts are not survival probabilities."))
